import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import puppeteer from "puppeteer-core";
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SCRATCH = process.env.SCRATCH || __dirname;
const CHROME = "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe";
const file = path.join(__dirname, "..", process.argv[2] || "SignFlow-Launch-Email-gold.html");
const sleep = ms => new Promise(r => setTimeout(r, ms));
const browser = await puppeteer.launch({ executablePath: CHROME, headless: "new", args: ["--no-sandbox", "--hide-scrollbars"] });
const page = await browser.newPage();
const bad = [];
page.on("requestfailed", r => { if (/\.(png|jpg|jpeg)/i.test(r.url())) bad.push("FAIL " + r.url()); });
page.on("response", r => { if (/\.(png|jpg|jpeg)/i.test(r.url()) && r.status() >= 400) bad.push(r.status() + " " + r.url()); });
await page.setViewport({ width: 620, height: 1000, deviceScaleFactor: 1 });
await page.goto(pathToFileURL(file).href, { waitUntil: "networkidle2" });
await sleep(1500);
await page.screenshot({ path: path.join(SCRATCH, "email-live-render.png"), fullPage: true });
await browser.close();
console.log(bad.length ? ("IMAGE ISSUES:\n" + [...new Set(bad)].join("\n")) : "all images loaded from the live domain OK");
